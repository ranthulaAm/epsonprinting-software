"""
Lexicon management and candidate correction suggestions.
Loads bundled Sinhala and English dictionaries and weights candidate
corrections using the empirical confusion table generated by the benchmark.
"""

import os
import json
import re

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
SINHALA_LEXICON_PATH = os.path.join(DATA_DIR, "sinhala_lexicon.txt")
CONFUSION_MATRIX_PATH = os.path.join(DATA_DIR, "confusion_matrix.json")

SINHALA_LEXICON = set()
ENGLISH_LEXICON = set()
CONFUSION_MATRIX = {}   # (src_char, dst_char) -> weight (lower cost for frequent OCR confusion)

# Try loading SymSpell for English
SYM_SPELL = None
try:
    from symspellpy import SymSpell, Verbosity
    SYM_SPELL = SymSpell(max_dictionary_edit_distance=2, prefix_length=7)
    # Load default symspell frequency dictionary
    import symspellpy
    dict_path = os.path.join(os.path.dirname(symspellpy.__file__), "frequency_dictionary_en_82_765.txt")
    if os.path.exists(dict_path):
        SYM_SPELL.load_dictionary(dict_path, term_index=0, count_index=1)
except Exception:
    SYM_SPELL = None


def load_lexicons():
    global SINHALA_LEXICON, ENGLISH_LEXICON, CONFUSION_MATRIX
    # Sinhala lexicon
    if os.path.exists(SINHALA_LEXICON_PATH):
        with open(SINHALA_LEXICON_PATH, "r", encoding="utf-8") as f:
            SINHALA_LEXICON = {line.strip() for line in f if line.strip()}

    # English fallback lexicon if SymSpell dictionary isn't active
    common_en = [
        "the", "be", "to", "of", "and", "a", "in", "that", "have", "i", "it", "for", "not", "on", "with",
        "he", "as", "you", "do", "at", "this", "but", "his", "by", "from", "they", "we", "say", "her",
        "she", "or", "an", "will", "my", "one", "all", "would", "there", "their", "what", "so", "up",
        "out", "if", "about", "who", "get", "which", "go", "me", "when", "make", "can", "like", "time",
        "no", "just", "him", "know", "take", "people", "into", "year", "your", "good", "some", "could",
        "them", "see", "other", "than", "then", "now", "look", "only", "come", "its", "over", "think",
        "also", "back", "after", "use", "two", "how", "our", "work", "first", "well", "way", "even",
        "new", "want", "because", "any", "these", "give", "day", "most", "us", "date", "name", "signature",
        "report", "document", "total", "amount", "price", "reference", "ref", "tel", "email", "phone",
        "department", "ministry", "republic", "sri", "lanka", "page", "number", "invoice", "cashier", "receipt"
    ]
    ENGLISH_LEXICON = set(common_en)

    # Confusion matrix
    if os.path.exists(CONFUSION_MATRIX_PATH):
        try:
            with open(CONFUSION_MATRIX_PATH, "r", encoding="utf-8") as f:
                CONFUSION_MATRIX = json.load(f)
        except Exception:
            CONFUSION_MATRIX = {}


load_lexicons()


def detect_script(text: str) -> str:
    """Classifies script: 'sin', 'eng', 'num', 'mixed', 'punct'."""
    has_sin = any(0x0D80 <= ord(c) <= 0x0DFF for c in text)
    has_eng = any(('a' <= c <= 'z' or 'A' <= c <= 'Z') for c in text)
    has_num = any('0' <= c <= '9' for c in text)

    if has_sin and has_eng:
        return "mixed"
    if has_sin:
        return "sin"
    if has_eng:
        return "eng"
    if has_num:
        return "num"
    return "punct"


def get_sub_cost(c1: str, c2: str) -> float:
    """Returns confusion-weighted substitution cost (0.0 < cost <= 1.0)."""
    if c1 == c2:
        return 0.0
    key = f"{c1}->{c2}"
    inv_key = f"{c2}->{c1}"
    if key in CONFUSION_MATRIX:
        # Frequent confusion has lower cost (e.g. 0.2 to 0.5)
        return max(0.2, 1.0 - CONFUSION_MATRIX[key])
    if inv_key in CONFUSION_MATRIX:
        return max(0.2, 1.0 - CONFUSION_MATRIX[inv_key])
    return 1.0


def weighted_levenshtein(s1: str, s2: str) -> float:
    """Calculates Levenshtein distance using empirical substitution costs."""
    m, n = len(s1), len(s2)
    dp = [[0.0] * (n + 1) for _ in range(m + 1)]

    for i in range(m + 1):
        dp[i][0] = float(i)
    for j in range(n + 1):
        dp[0][j] = float(j)

    for i in range(1, m + 1):
        c1 = s1[i - 1]
        for j in range(1, n + 1):
            c2 = s2[j - 1]
            cost = get_sub_cost(c1, c2)
            dp[i][j] = min(
                dp[i - 1][j] + 1.0,        # deletion
                dp[i][j - 1] + 1.0,        # insertion
                dp[i - 1][j - 1] + cost    # substitution
            )
    return dp[m][n]


PUNCT_TRIM = re.compile(r'^[^\w\u0d80-\u0dff\u200d]+|[^\w\u0d80-\u0dff\u200d]+$')

def clean_word(word: str) -> str:
    return PUNCT_TRIM.sub('', word).strip()


def suggest_candidates(word: str, max_candidates: int = 3) -> list[str]:
    """Finds top candidate suggestions from lexicons using weighted edit distance."""
    clean = clean_word(word)
    if not clean or len(clean) < 2:
        return []

    script = detect_script(clean)
    candidates = []

    if script == "sin":
        for cand in SINHALA_LEXICON:
            # Length filter optimization
            if abs(len(cand) - len(clean)) > 2:
                continue
            dist = weighted_levenshtein(clean, cand)
            if dist <= 2.2:
                candidates.append((cand, dist))
        candidates.sort(key=lambda x: x[1])
        return [c[0] for c in candidates[:max_candidates]]

    elif script == "eng":
        if SYM_SPELL:
            sym_suggestions = SYM_SPELL.lookup(clean.lower(), Verbosity.CLOSEST, max_edit_distance=2)
            if sym_suggestions:
                return [s.term for s in sym_suggestions[:max_candidates]]
        for cand in ENGLISH_LEXICON:
            if abs(len(cand) - len(clean)) > 2:
                continue
            dist = weighted_levenshtein(clean.lower(), cand)
            if dist <= 2.0:
                candidates.append((cand, dist))
        candidates.sort(key=lambda x: x[1])
        return [c[0] for c in candidates[:max_candidates]]

    return []


def is_known_word(word: str) -> bool:
    """Checks if a clean word is in the bundled Sinhala or English lexicon."""
    clean = clean_word(word)
    if not clean:
        return True
    if clean.isdigit():
        return True
    if clean in SINHALA_LEXICON:
        return True
    if clean.lower() in ENGLISH_LEXICON:
        return True
    if SYM_SPELL and clean.lower() in SYM_SPELL.words:
        return True
    return False
